import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {randomUUID} from 'node:crypto';
import {openDatabase} from '../server/persistence/database.js';
import {sendChatMessage} from '../server/conversation/chat.js';
import {getSemanticState} from '../server/reasoning/semantic-core.js';
import {inspectBrazilianCityCoverage} from '../server/conversation/conversation-feedback.js';
const folder=mkdtempSync(join(tmpdir(),'mylittlia-v0284-'));
const db=openDatabase(join(folder,'test.db'),{seed:false});
const add=(s,p,o)=>db.prepare(`INSERT INTO knowledge_relations(id,subject,predicate,object,source_type) VALUES (?,?,?,?,?)`).run(randomUUID(),s,p,o,'test');
try {
  add('brasil','tem','pais federativo');
  add('pernambuco','tem','municipio_populoso_de_referencia_recife');
  add('sao_paulo','tem','municipio_populoso_de_referencia_campinas');
  let answer=sendChatMessage(db,{text:'qual a cidade mais populosa do Brasil?'});
  let id=answer.conversationId;
  assert.equal(getSemanticState(db,id).property,'population','mais populosa é critério de população');
  assert.doesNotMatch(answer.reply,/por população, extensão territorial ou PIB/i,'não deve pedir critério já expresso');
  const comment='Mas vc tem das 10 maiores por estados brasileiros, logo pode ver qual a que tem maior população e inferir esta resposta';
  answer=sendChatMessage(db,{conversationId:id,text:comment});
  assert.equal(answer.result.kind,'semantic-reasoning-feedback');
  assert.match(answer.reply,/compar|conheço|conhece|sugerir/i);
  assert.doesNotMatch(answer.reply,/escala de 0 a 100|informação fresquinha|não sei responder/i);
  assert.equal(getSemanticState(db,id).property,'population');
  assert.equal(db.prepare('SELECT count(*) n FROM conversational_teachings').get().n,0);
  assert.equal(db.prepare('SELECT COUNT(*) n FROM knowledge_relations').get().n,3);
  const follow=sendChatMessage(db,{conversationId:id,text:'população'});
  assert.equal(getSemanticState(db,id).property,'population');
  assert.doesNotMatch(follow.reply,/escala de 0 a 100/);
  assert.equal(inspectBrazilianCityCoverage(db).referenceCount,2);
  add('recife','pertence_a','pernambuco');add('recife','populacao','1.500.000 habitantes em 2025');
  add('campinas','pertence_a','sao paulo');add('campinas','populacao','1.100.000 habitantes em 2025');
  let answer2=sendChatMessage(db,{text:'qual a cidade mais populosa do Brasil?'});
  assert.match(answer2.reply,/Recife/i);
  assert.match(answer2.reply,/apenas|somente|conheço|dados dispon/i);
  answer2=sendChatMessage(db,{conversationId:answer2.conversationId,text:comment});
  assert.match(answer2.reply,/Recife/);
  assert.match(answer2.reply,/parcial/);
  console.log('PASS: v0.28.4 feedback não é ensino, critério explícito e verificação de medidas do SQLite');
} finally {db.close();rmSync(folder,{recursive:true,force:true});}
