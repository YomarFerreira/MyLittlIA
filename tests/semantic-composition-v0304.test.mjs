import assert from 'node:assert/strict';
import {mkdtempSync, rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {openDatabase} from '../server/persistence/database.js';
import {propertyQueryAnswer} from '../server/reasoning/property-query.js';
const dir=mkdtempSync(join(tmpdir(),'mylittlia-semantic-'));
try {
 const path=join(dir,'test.sqlite');
 let db=openDatabase(path,{seed:false});
 const add=(subject,predicate,object)=>db.prepare('INSERT INTO knowledge_relations(id,subject,predicate,object) VALUES (lower(hex(randomblob(16))),?,?,?)').run(subject,predicate,object);
 add('cachorro','numero_patas_tipico','4');
 add('cachorro','revestimento','pelos');
 add('cachorro','caracteristica','pelos');
 add('cachorro','e_um','mamifero');
 add('mamifero','respira_por','pulmoes');
 add('gato','bebe','agua');
 add('capivara','habitat','margens_de_rios');
 add('borboleta','cor_tipica','diversas_cores');
 add('vaca','e_um','herbivoro');
 add('herbivoro','come','plantas');
 let r=propertyQueryAnswer(db,'Sim, quais características de um cachorro?');
 assert.ok(r, 'deve obter características do cachorro');
 assert.match(r.answer,/quatro patas/);
 assert.match(r.answer,/pelos/);
 assert.doesNotMatch(r.answer,/conheço:\s*4,\s*pelos/i);
 assert.ok(r.path.some(x=>x.predicate==='numero_patas_tipico'));
 assert.ok(r.path.some(x=>x.predicate==='revestimento'));
 assert.match(propertyQueryAnswer(db,'O que o gato bebe?').answer,/agua/);
 assert.match(propertyQueryAnswer(db,'Onde vive a capivara?').answer,/margens de rios/);
 assert.match(propertyQueryAnswer(db,'Como o mamifero respira?').answer,/pulmoes/);
 assert.match(propertyQueryAnswer(db,'O que a vaca come?').answer,/plantas/);
 assert.equal(propertyQueryAnswer(db,'Qual a cor do cachorro?'),null);
 assert.match(propertyQueryAnswer(db,'Qual a cor da borboleta?').answer,/diversas cores/);
 db.prepare("UPDATE conversational_templates SET template_text='Resposta editada: {values}' WHERE template_key='property-color'").run();
 assert.match(propertyQueryAnswer(db,'Qual a cor da borboleta?').answer,/Resposta editada/);
 db.prepare("UPDATE semantic_predicate_phrases SET template_text='tem {count} membros' WHERE property='features' AND predicate='numero_patas_tipico'").run();
 assert.match(propertyQueryAnswer(db,'Quais características do cachorro?').answer,/quatro membros/);
 db.close();
 db=openDatabase(path,{seed:false});
 assert.match(propertyQueryAnswer(db,'Quais características do cachorro?').answer,/quatro membros/);
 assert.equal(db.prepare('SELECT count(*) AS n FROM schema_migrations WHERE version=15').get().n,1);
 db.close();
 console.log('v0.30.4: composição, consulta, ausência de fatos, templates editáveis e persistência OK');
} finally {rmSync(dir,{recursive:true,force:true});}
