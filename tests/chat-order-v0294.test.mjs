import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {openDatabase} from '../server/persistence/database.js';
import {getChatOrder,setChatOrder} from '../server/conversation/chat-preferences.js';
import {sendChatMessage,conversationHistory} from '../server/conversation/chat.js';
import {groupChatTurns,orderedChatTurns,parseChatTimestamp,formatChatTimestamp} from '../js/chat-view.js';
const dir=mkdtempSync(join(tmpdir(),'mylittlia-v0294-'));
const path=join(dir,'chat.db');
try {
  let db=openDatabase(path,{seed:false});
  assert.ok(db.prepare('SELECT MAX(version) v FROM schema_migrations').get().v>=11);
  assert.equal(getChatOrder(db),'newest');
  assert.equal(setChatOrder(db,'oldest'),'oldest');
  assert.throws(()=>setChatOrder(db,'reverse'),/inválida/i);
  assert.equal(getChatOrder(db),'oldest');
  const first=sendChatMessage(db,{text:'Olá'});
  assert.equal(first.messages.length,2);
  assert.deepEqual(first.messages.map(m=>m.role),['user','assistant']);
  assert.ok(first.messages.every(m=>m.created_at));
  const second=sendChatMessage(db,{text:'Quem é você?',conversationId:first.conversationId});
  const history=conversationHistory(db,first.conversationId);
  assert.equal(history.length,4);
  const turns=groupChatTurns(history);
  assert.equal(turns.length,2);
  assert.deepEqual(turns.map(t=>t.map(m=>m.role)),[['user','assistant'],['user','assistant']]);
  assert.equal(orderedChatTurns(history,'newest')[0][0].content,'Quem é você?');
  assert.equal(orderedChatTurns(history,'newest')[0][1].content,second.reply);
  assert.ok(first.messages.every(m=>/\.\d{3}Z$/.test(m.created_at)),'novas mensagens registradas com milissegundos');
  assert.ok(Date.parse(first.messages[1].created_at)>Date.parse(first.messages[0].created_at),'resposta depois da pergunta mesmo no mesmo milissegundo');
  assert.ok(first.messages.every(m=>m.created_at.endsWith('Z') && m.created_at.includes('.')));
  assert.match(formatChatTimestamp(first.messages[0].created_at),/\d{2}:\d{2}:\d{2}\.\d{3}/);
  assert.equal(orderedChatTurns(history,'oldest')[0][0].content,'Olá');
  assert.equal(conversationHistory(db,first.conversationId)[0].content,'Olá','apresentação não modifica a ordem cronológica persistida');
  assert.equal(parseChatTimestamp('2026-11-02 19:30:00').toISOString(),'2026-11-02T19:30:00.000Z');
  assert.match(formatChatTimestamp('2026-11-02 19:30:00','pt-BR','America/Recife'),/02\/11\/2026.*16:30:00$/);
  assert.doesNotMatch(formatChatTimestamp('2026-11-02 19:30:00'),/\.000$/,'não inventar milissegundos do histórico legado');
  assert.match(formatChatTimestamp('2026-11-02T19:30:00.157Z','pt-BR','America/Recife'),/16:30:00\.157$/);
  assert.equal(formatChatTimestamp('sem data'),'Horário indisponível');
  assert.deepEqual(orderedChatTurns(history,'newest').map(t=>t.map(m=>m.role)),[['user','assistant'],['user','assistant']]);
  db.close();
  db=openDatabase(path,{seed:false});
  assert.equal(getChatOrder(db),'oldest','preferência persiste entre sessões');
  assert.equal(conversationHistory(db,first.conversationId).length,4);
  assert.equal(setChatOrder(db,'newest'),'newest');
  db.close();
  console.log('PASS: ordenação nos dois sentidos, grupos de perguntas/respostas, timestamps e preferência SQLite v11');
} finally {rmSync(dir,{recursive:true,force:true});}
